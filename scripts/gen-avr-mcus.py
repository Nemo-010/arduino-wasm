#!/usr/bin/env python3
"""Generate web/avr-mcus.js: AVR device -> (architecture, device macro).

The wasm cc1plus in build/avr-tools accepts architecture names (avr2, avr25,
avr5, ...) but not device names: it was built without GCC's device table, so
`-mmcu=atmega328p` is rejected and only `-mmcu=avr5` works. Two things the
device name is still needed for:

  * avr-libc's <avr/io.h> picks the register header from a device macro such as
    __AVR_ATmega328P__, so the macro has to be defined on the command line;
  * the startup object and the linker script are chosen per architecture, but
    the startup object's name contains the device (crtatmega328p.o).

Both facts are in GCC's own avr-mcus.def, so the table is generated from the
same GCC release the wasm build came from rather than typed in by hand.

    python3 scripts/gen-avr-mcus.py [--gcc 7.3.0]

Writes web/avr-mcus.js, which is committed: the page loads no compiler-side
data over the network.
"""

import argparse
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "web", "avr-mcus.js")
CACHE = os.path.join(ROOT, "build", "avr-mcus.def")

URL = "https://raw.githubusercontent.com/gcc-mirror/gcc/releases/gcc-{version}/gcc/config/avr/avr-mcus.def"

# AVR_MCU (NAME, ARCH, DEV_ATTRIBUTE, MACRO, DATA_SEC, N_FLASH)
ENTRY = re.compile(r"^AVR_MCU \(([^,]+),\s*([A-Za-z0-9_]+),\s*[^,]+,\s*([^,]+),")


def fetch(version):
    if os.path.exists(CACHE) and os.path.getsize(CACHE) > 0:
        return CACHE
    url = URL.format(version=version)
    print("fetching " + url)
    with urllib.request.urlopen(url, timeout=120) as response:
        body = response.read()
    os.makedirs(os.path.dirname(CACHE), exist_ok=True)
    with open(CACHE, "wb") as handle:
        handle.write(body)
    return CACHE


def unquote(token):
    token = token.strip()
    if token == "NULL":
        return None
    if token.startswith('"') and token.endswith('"'):
        return token[1:-1]
    return token


def parse(path):
    devices = {}
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            match = ENTRY.match(line)
            if not match:
                continue
            name = unquote(match.group(1))
            arch = unquote(match.group(2))
            macro = unquote(match.group(3))
            if name is None or arch is None:
                continue
            arch = arch.replace("ARCH_", "").lower()
            devices[name] = (arch, macro)
    return devices


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--gcc", default="7.3.0")
    args = parser.parse_args()

    devices = parse(fetch(args.gcc))
    if len(devices) < 100:
        sys.exit("only %d devices parsed: avr-mcus.def changed shape" % len(devices))

    arches = sorted({arch for arch, _ in devices.values()})
    lines = [
        "// Generated by scripts/gen-avr-mcus.py from GCC %s's" % args.gcc,
        "// gcc/config/avr/avr-mcus.def. Do not edit.",
        "//",
        "// device -> [architecture, device macro]. The macro is the one avr-libc's",
        "// <avr/io.h> tests for, so its spelling is load-bearing.",
        "",
        "export const AVR_DEVICES = {",
    ]
    for name in sorted(devices):
        arch, macro = devices[name]
        lines.append('  %s: [%s, %s],' % ('"' + name + '"', '"' + arch + '"', "null" if macro is None else '"' + macro + '"'))
    lines.append("};")
    lines.append("")
    lines.append("export const AVR_ARCHES = " + repr(arches).replace("'", '"') + ";")
    lines.append("")

    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print("wrote %s: %d devices, %d architectures" % (OUT, len(devices), len(arches)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
